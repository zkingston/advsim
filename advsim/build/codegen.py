"""Write `advsim/engine/_generated/` from the built artifacts.

Nothing here is hand-edited; tests/test_build_dex.py regenerates and fails on a diff. The engine
imports only these modules and Warp, which is what keeps IDs out of hand-written
kernel code.
"""
from __future__ import annotations

import pathlib

from advsim import artifacts, fileio
from advsim.build.build_pool import COLUMNS
from advsim.engine import layout

GENERATED = fileio.ROOT / 'advsim' / 'engine' / '_generated'
HEADER = '"""Generated by advsim/build/codegen.py. Do not edit."""\n'
ID_TABLES = ('species', 'moves', 'abilities', 'items', 'conditions')
# Each enum's constant prefix: ids.TYPE_FIRE, ids.CATEGORY_STATUS, ids.FLAG_CONTACT.
ENUMS = {'types': 'TYPE', 'stats': 'STAT', 'weather': 'WEATHER', 'categories': 'CATEGORY',
         'targets': 'TARGET', 'genders': 'GENDER', 'move_flags': 'FLAG'}


def _const(name: str) -> str:
    """A Python identifier for a dex name: 'hiddenpower' -> HIDDENPOWER, '' -> X."""
    out = ''.join(c if c.isalnum() else '_' for c in name.upper())
    return f'X{out}' if not out or out[0].isdigit() else out


def ids_module(ids: dict[str, list[str]]) -> str:
    lines = [HEADER]
    for table in ID_TABLES:
        names = ids[table]
        lines.append(f'\n# {table}: {len(names) - 1} entries plus 0 = none')
        lines.append(f'N_{table.upper()} = {len(names)}')
        prefix = {'species': 'SPECIES', 'moves': 'MOVE', 'abilities': 'ABILITY',
                  'items': 'ITEM', 'conditions': 'COND'}[table]
        for i, name in enumerate(names):
            lines.append(f'{prefix}_{_const(name) if name else "NONE"} = {i}')
    for enum, prefix in ENUMS.items():
        lines.append(f'\n# {enum}')
        for i, name in enumerate(ids[enum]):
            value = 1 << i if enum == 'move_flags' else i
            lines.append(f'{prefix}_{_const(name)} = {value}')
    for kind in ('move_families', 'ability_families', 'item_families'):
        lines.append(f'\n# {kind}: 0 = data only')
        for i, name in enumerate(ids[kind], start=1):
            lines.append(f'{kind.split("_")[0].upper()}FAM_{_const(name)} = {i}')
    lines.append(f'\n# pool.npz: a Pokemon\'s {len(COLUMNS)} int16 columns (build/build_pool.py)')
    lines.append(f'POOL_WIDTH = {len(COLUMNS)}')
    for i, name in enumerate(COLUMNS):
        lines.append(f'POOL_{_const(name)} = {i}')
    return '\n'.join(lines) + '\n'


WARP_DTYPE = {'u8': 'wp.uint8', 'u16': 'wp.uint16', 'u32': 'wp.uint32'}


def state_module() -> str:
    """The Warp struct for battle state, derived from engine/layout.py.

    Storage keeps the declared widths: narrow storage is what keeps a slot
    copy cheap, the cost that matters for search.
    """
    lines = [HEADER, 'import warp as wp', '', '', '@wp.struct', 'class State:']
    for f in layout.FIELDS:
        ndim = 1 + len(layout.SHAPES[f.scope]) + (1 if f.width > 1 else 0)
        kind = 'wp.array' if ndim == 1 else f'wp.array{ndim}d'
        shape = ''.join(f'[{d}]' for d in layout.SHAPES[f.scope]) + (f'[{f.width}]' if f.width > 1 else '')
        note = f'  # [B]{shape}' + (f' {f.note}' if f.note else '')
        lines.append(f'    {f.name}: {kind}(dtype={WARP_DTYPE[f.dtype]}){note}')
    # Every field of one battle back to zero: what auto-reset starts from, and
    # a new field is covered the moment it is in the layout.
    lines += ['', '', '@wp.func', 'def clear_battle(s: State, b: int):']
    for f in layout.FIELDS:
        dims = list(layout.SHAPES[f.scope]) + ([f.width] if f.width > 1 else [])
        idx = ['b']
        indent = '    '
        for k, d in enumerate(dims):
            lines.append(f'{indent}for i{k} in range({d}):')
            idx.append(f'i{k}')
            indent += '    '
        lines.append(f'{indent}s.{f.name}[{", ".join(idx)}] = {WARP_DTYPE[f.dtype]}(0)')
    # One battle's every field onto another slot: `fork`, and a new field is
    # carried the moment it is in the layout. Loop bounds come from the array
    # shapes so Warp keeps the loops: Warp unrolls constant ranges up to 16,
    # and unrolled this one function is thousands of lines of CUDA.
    lines += ['', '', '@wp.func', 'def copy_battle(s: State, src: int, dst: int):']
    for f in layout.FIELDS:
        dims = list(layout.SHAPES[f.scope]) + ([f.width] if f.width > 1 else [])
        idx = []
        indent = '    '
        for k, d in enumerate(dims):
            lines.append(f'{indent}for i{k} in range(s.{f.name}.shape[{k + 1}]):')
            idx.append(f'i{k}')
            indent += '    '
        tail = ''.join(f', {i}' for i in idx)
        lines.append(f'{indent}s.{f.name}[dst{tail}] = s.{f.name}[src{tail}]')
    # One Pokemon's every field to another battle and party slot: how
    # `determinize` puts the foe's party in its canonical order.
    lines += ['', '', '@wp.func', 'def copy_mon(s: State, src: int, side: int, slot: int, dst: int, dst_slot: int):']
    for f in layout.FIELDS:
        if f.scope != layout.MON:
            continue
        if f.width > 1:
            lines.append(f'    for i in range(s.{f.name}.shape[3]):')
            lines.append(f'        s.{f.name}[dst, side, dst_slot, i] = s.{f.name}[src, side, slot, i]')
        else:
            lines.append(f'    s.{f.name}[dst, side, dst_slot] = s.{f.name}[src, side, slot]')
    lines.append('')
    return '\n'.join(lines)


AXIS_NAMES = ('p', 'm', 'c')


def _fold(f: layout.Field, off: int) -> list[str]:
    """The lines that fold one field's words into `h`, innermost loop last."""
    if f.dtype[0] != 'u':
        raise ValueError(f'{f.name}: a signed field would sign-extend differently in NumPy')
    axes = list(layout.SHAPES[f.scope]) + ([f.width] if f.width > 1 else [])
    names = [AXIS_NAMES[i] for i in range(len(axes))]
    lines, term, stride = [], str(off), 1
    for i in reversed(range(len(axes))):
        term = f'{names[i]} * {stride} + ' + term if stride > 1 else f'{names[i]} + ' + term
        stride *= axes[i]
    for depth, (name, n) in enumerate(zip(names, axes)):
        lines.append('    ' * (depth + 1) + f'for {name} in range({n}):')
    read = f's.{f.name}[' + ', '.join(['b'] + names) + ']'
    lines.append('    ' * (len(axes) + 1) + f'h = h ^ hash_.word({term}, wp.uint32({read}))')
    return lines


def hashes_module() -> str:
    """The canonical hash, unrolled over the state layout.

    One u32 word per scalar in `layout.FIELDS` order; the word index salts the
    hash, so it is assigned over every field and the mask only decides which
    words are folded in.
    """
    offsets = layout.word_offsets()
    lines = [HEADER, 'import warp as wp', '',
             'from advsim.engine import hash as hash_',
             'from advsim.engine._generated.state import State', '',
             f'N_WORDS = {layout.N_WORDS}', '']
    for name, fields, doc in (('full_hash', layout.FULL, 'Every field but `err`: replay diffing against Showdown.'),
                              ('position_hash', layout.POSITION, 'Game-relevant fields only: transpositions, perft, world dedup.')):
        lines += ['', '@wp.func', f'def {name}(s: State, b: int) -> wp.uint64:',
                  f'    """{doc}"""', '    h = wp.uint64(0)']
        for f in fields:
            lines += _fold(f, offsets[f.name])
        lines += ['    return h', '']
    return '\n'.join(lines)


def generate(ids: dict[str, list[str]] | None = None) -> list[pathlib.Path]:
    ids = ids or artifacts.load_ids()
    written = []
    # layout.json is how export_state.js and the NumPy mirror learn the state
    # fields; engine/layout.py stays the only definition.
    fileio.write_json(fileio.ARTIFACTS / 'layout.json', layout.as_json())
    GENERATED.mkdir(parents=True, exist_ok=True)
    for name, text in (('__init__.py', HEADER), ('ids.py', ids_module(ids)),
                       ('state.py', state_module()),
                       ('hashes.py', hashes_module())):
        path = GENERATED / name
        fileio.write_text(path, text)
        written.append(path)
    return written
